import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def test_model_registry_declares_v9_research_only():
    registry = json.loads((ROOT / "models" / "model_registry.json").read_text(encoding="utf-8"))
    assert registry["active_runtime_model"] == "final"
    assert registry["versions"]["v8"]["status"] == "archived_unvalidated"
    assert registry["versions"]["final"]["status"] == "validated_research_backtest"


def test_web_benchmark_is_reproducible():
    chart = ROOT / "web" / "assets" / "charts" / "temporal_backtest_final.png"
    assert chart.exists() and chart.stat().st_size > 1_000


def test_archive_policy_points_to_active_research():
    policy = (ROOT / "ARCHIVE_STATUS.md").read_text(encoding="utf-8")
    notebook_status = (ROOT / "notebooks" / "ARCHIVE_STATUS.md").read_text(encoding="utf-8")
    assert "CarTheftRisk_final.ipynb" in policy
    assert "CarTheftRisk_final.ipynb" in notebook_status


def test_research_limitations_are_published():
    text = (ROOT / "docs" / "RESEARCH_LIMITATIONS.md").read_text(encoding="utf-8")
    assert "אינה חוזה אם רכב פרטי ייגנב" in text
    assert "אינה מקבלת הצעות מחיר חיות" in text


def test_research_status_separates_runtime_and_backtest():
    status = json.loads((ROOT / "web" / "assets" / "research_status.json").read_text(encoding="utf-8"))
    assert status["runtime_scores"]["model_version"] == "final"
    assert status["research_backtest"]["protocol"]["name"] == "one-step-ahead chronological backtest"
    assert status["insurance"]["status"] == "simulation_only"


def test_frontend_applies_v9_scores():
    html = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    assert "applyFinalScores" in html or "applyV9Scores" in html
    assert "assets/final_scores.json" in html
    assert "assets/embedded_data.js" in html


def test_reports_preserve_historical_research_but_lead_with_v9_status():
    process_report = (ROOT / "web" / "process_report.html").read_text(encoding="utf-8")
    agent_report = (ROOT / "web" / "agent_report.html").read_text(encoding="utf-8")
    index = (ROOT / "web" / "index.html").read_text(encoding="utf-8")
    assert 'id="v9-research-status"' in process_report
    assert 'id="v9-agent-status"' in agent_report
    assert "assets/charts/temporal_backtest_v9.png" in process_report or "assets/charts/temporal_backtest_final.png" in process_report
    assert "assets/embedded_data.js" in index
    embedded = (ROOT / "web" / "assets" / "embedded_data.js").read_text(encoding="utf-8")
    assert "Generated by src.temporal_validation.py" in embedded


def test_web_lookup_metadata_has_no_legacy_benchmark():
    data = json.loads((ROOT / "web" / "assets" / "data.json").read_text(encoding="utf-8"))
    assert data["metadata"]["runtime_model_version"] == "final"
    assert "model_benchmark" not in data["metadata"]
